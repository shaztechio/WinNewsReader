using System.Text;
using WinNewsReader.Store;

namespace WinNewsReader.Core;

/// <summary>
/// NetNewsWire's <c>OPMLExporter</c>: top-level feeds, then folders, each sorted by name the way Finder sorts.
/// A feed in several places is written in each of them.
/// </summary>
public static class OpmlExporter
{
	public static string OpmlString(ArticlesStore store, string title)
	{
		var s = new StringBuilder();
		s.Append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- OPML generated by WinNewsReader -->\n<opml version=\"1.1\">\n<head>\n");
		s.Append($"<title>{Escaped(title)}</title>\n</head>\n<body>\n");
		foreach (var feed in store.GetTopLevelFeeds().SortedByName())
		{
			AppendFeed(s, feed, 1);
		}
		foreach (var folder in store.GetFolders().SortedByName())
		{
			var name = Escaped(folder.Name);
			var feeds = store.GetFeeds(folder.FolderId).SortedByName().ToList();
			if (feeds.Count == 0)
			{
				s.Append($"\t<outline text=\"{name}\" title=\"{name}\"/>\n");
				continue;
			}
			s.Append($"\t<outline text=\"{name}\" title=\"{name}\">\n");
			foreach (var feed in feeds)
			{
				AppendFeed(s, feed, 2);
			}
			s.Append("\t</outline>\n");
		}
		s.Append("</body>\n</opml>");
		return s.ToString();
	}

	private static void AppendFeed(StringBuilder s, StoredFeed feed, int indentLevel)
	{
		var name = Escaped(NameSorting.DisplayName(feed));
		s.Append('\t', indentLevel);
		s.Append(
			$"<outline text=\"{name}\" title=\"{name}\" description=\"\" type=\"rss\" version=\"RSS\" " +
			$"htmlUrl=\"{Escaped(feed.HomePageUrl ?? "")}\" xmlUrl=\"{Escaped(feed.Url)}\"/>\n");
	}

	/// <summary>RSCore's <c>escapingSpecialXMLCharacters</c>.</summary>
	private static string Escaped(string text) =>
		text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\"", "&quot;").Replace("'", "&apos;");
}
